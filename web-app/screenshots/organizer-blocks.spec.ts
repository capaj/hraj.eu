import { test, expect } from './fixtures'

test('organizers can confirm a block, recover from errors, and unblock a player', async ({ page, capture }) => {
  await page.goto('/scenarios/organizer-blocks')
  await expect(page.locator('html')).toHaveAttribute('data-hydrated', 'true')
  const blockPetr = page.getByRole('button', { name: 'Zablokovat hráče Petr Novák ze všech mých událostí', exact: true })
  await blockPetr.click()
  const dialog = page.getByRole('dialog', { name: 'Zablokovat hráče Petr Novák?' })
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText('přímý odkaz')
  await expect(dialog).toContainText('odběrů míst a měst')
  await capture('organizer-block-confirmation', dialog)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(blockPetr).toBeFocused()
  await page.getByLabel('Simulate save failure').check()
  await blockPetr.click()
  await dialog.getByRole('button', { name: 'Zablokovat ze všech mých událostí', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Odblokovat hráče Petr Novák', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Zrušit', exact: true }).click()
  await page.getByLabel('Simulate save failure').uncheck()
  await blockPetr.click()
  await dialog.getByRole('button', { name: 'Zablokovat ze všech mých událostí', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const unblock = page.getByRole('button', { name: 'Odblokovat hráče Petr Novák', exact: true })
  await expect(unblock).toBeVisible()
  await expect(blockPetr).toHaveCount(0)
  await capture('organizer-blocked-players')
  await unblock.click()
  await expect(unblock).toHaveCount(0)
  await expect(blockPetr).toBeVisible()
  await page.getByRole('textbox', { name: 'Zablokovat hráče', exact: true }).fill('Anna')
  await expect(page.getByRole('button', { name: 'Zablokovat hráče Anna Dvořáková ze všech mých událostí', exact: true })).toHaveCount(2)
})

test('a blocked direct link only shows the denial page', async ({ page, capture }) => {
  await page.goto('/scenarios/organizer-blocks?blocked=true')
  await expect(page.locator('html')).toHaveAttribute('data-hydrated', 'true')
  await expect(page.getByRole('heading', { name: 'Organizátor vás zablokoval.', exact: true })).toBeVisible()
  await expect(page.getByRole('main')).not.toContainText('Petr Novák')
  await expect(page.getByRole('main')).not.toContainText('Kdo hraje')
  await expect(page.getByRole('link', { name: 'Najít jiné události', exact: true })).toBeVisible()
  await capture('organizer-blocked-event', page.getByRole('main'))
})
