import { test, expect } from './fixtures'

test('one header action requires selecting a player and supports retry and unblock', async ({ page, capture }) => {
  await page.goto('/scenarios/organizer-blocks')
  await expect(page.locator('html')).toHaveAttribute('data-hydrated', 'true')
  const players = page.getByTestId('event-players')
  const block = players.getByRole('button', { name: 'Zablokovat hráče', exact: true })
  const heading = players.getByRole('button', { name: 'Kdo hraje', exact: true })
  await expect(block).toHaveCount(1)
  await expect(players.getByRole('button', { name: /Zablokovat hráče .* ze všech/ })).toHaveCount(0)
  await expect(page.getByTestId('pending-players').getByRole('button', { name: /Zablokovat/ })).toHaveCount(0)
  await capture('event-players-block-action', players)
  await block.click()
  // The header's expand/collapse control must not receive the modal's clicks.
  await expect(heading).toHaveAttribute('aria-expanded', 'true')
  const dialog = page.getByRole('dialog', { name: 'Zablokovat hráče', exact: true })
  const select = dialog.getByRole('combobox', { name: 'Hráč k zablokování', exact: true })
  const save = dialog.getByRole('button', { name: 'Zablokovat ze všech mých událostí', exact: true })
  await expect(dialog).toBeVisible()
  await expect(select).toBeFocused()
  await expect(select).toHaveValue('')
  await expect(save).toBeDisabled()
  await expect(select.getByRole('option', { name: 'Jan Svoboda', exact: true })).toHaveCount(1)
  await capture('event-block-player-picker', dialog)
  await select.selectOption('petr')
  await expect(save).toBeEnabled()
  await expect(dialog).toContainText('přímý odkaz')
  await expect(dialog).toContainText('odběrů míst a měst')
  await capture('organizer-block-confirmation', dialog)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(block).toBeFocused()
  await page.getByLabel('Simulate save failure').check()
  await block.click()
  await expect(select).toHaveValue('')
  await expect(save).toBeDisabled()
  await select.selectOption('petr')
  await save.click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await expect(players).toContainText('Petr Novák')
  await dialog.getByRole('button', { name: 'Zrušit', exact: true }).click()
  await page.getByLabel('Simulate save failure').uncheck()
  await block.click()
  await select.selectOption('petr')
  await save.click()
  await expect(dialog).toHaveCount(0)
  const unblock = page.getByRole('button', { name: 'Odblokovat hráče Petr Novák', exact: true })
  await expect(unblock).toBeVisible()
  await expect(players).not.toContainText('Petr Novák')
  await expect(players).toContainText('Anna Dvořáková')
  await capture('organizer-blocked-players')
  await unblock.click()
  await expect(unblock).toHaveCount(0)
  await expect(players).toContainText('Petr Novák')
  // Pending-payment players are available through the same single action.
  await block.click()
  await select.selectOption('jan')
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByTestId('pending-players')).not.toContainText('Jan Svoboda')
  await expect(page.getByRole('button', { name: 'Odblokovat hráče Jan Svoboda', exact: true })).toBeVisible()
  // Profile search still supports blocking a specific player directly.
  await page.getByRole('textbox', { name: 'Zablokovat hráče', exact: true }).fill('Anna')
  const profileBlock = page.getByRole('button', { name: 'Zablokovat hráče Anna Dvořáková ze všech mých událostí', exact: true })
  await expect(profileBlock).toHaveCount(1)
  await profileBlock.click()
  const profileDialog = page.getByRole('dialog', { name: 'Zablokovat hráče Anna Dvořáková?', exact: true })
  await expect(profileDialog.getByRole('combobox')).toHaveCount(0)
  await expect(profileDialog.getByRole('button', { name: 'Zablokovat ze všech mých událostí', exact: true })).toBeEnabled()
  await page.keyboard.press('Escape')
})

test('a blocked direct link only shows the denial page', async ({ page, capture }) => {
  await page.goto('/scenarios/organizer-blocks?blocked=true')
  await expect(page.locator('html')).toHaveAttribute('data-hydrated', 'true')
  await expect(page.getByRole('heading', { name: 'Organizátor vás zablokoval.', exact: true })).toBeVisible()
  await expect(page.getByRole('main')).not.toContainText('Petr Novák')
  await expect(page.getByRole('main')).not.toContainText('Kdo hraje')
  await expect(page.getByRole('link', { name: 'Najít jiné události', exact: true })).toBeVisible()
  await capture('organizer-blocked-event', page.getByRole('main'))
})
